/**
 * Fonction de traduction robuste
 * Trie les clés pour traduire les phrases longues avant les mots seuls
 */
function traduire(texte) {
    if (!texte) return "";
    
    let cle = texte.toString().trim().toUpperCase().replace(/\.$/, "");
    
    // 1. Recherche directe dans le dictionnaire
    if (typeof dictionnaireWF !== 'undefined' && dictionnaireWF[cle]) {
        return dictionnaireWF[cle];
    }

    // 2. Sécurité pour les malus de 1999 (Amir & Aoi)
    if (cle.includes("AMIR") && cle.includes("AOI")) {
        return "MALUS : FACEOFF (1999)";
    }

    // 3. Sécurité pour les factions
    if (cle.includes("MURMURS")) return "LES MURMURES";
    if (cle.includes("TECHROT")) return "TECHNOCYTE";

    // 4. SI ON NE TROUVE RIEN : On renvoie le texte original (ex: "Enemies")
    // Au moins, ce sera en anglais mais pas marqué "INCONNU"
    return texte; 
}

